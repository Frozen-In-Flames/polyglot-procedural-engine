// demo/deadramp.ts - "DeadRamp Building": one build record from the
// DeadRamp Base catalog, fitted and regenerated as a procedural
// district by the engine's city converter.
//
// The page fetches one exported build record (public/deadramp/
// accounting-l2.json, exported from data/base-catalog.json in the
// deadramp-base repository), converts it to the layout form with
// layoutFromDeadRampBuild (one building per manifest entry, size and
// height from the entry's byte count), fits it with fitCitySpec, and
// renders the city buildCity regenerates from the fitted spec alone.
// The panel grades the regenerated city against the spec with the
// suite's own statistics oracle (checkCityStats). The record is
// data; every building on screen is generated by the engine.
import {
  fitCitySpec, buildCity, measureCity, checkCityStats, cityDigest,
  type BuiltCity,
} from '../src/index.js';
import {
  layoutFromDeadRampBuild, type DeadRampBuildRecord,
} from '../src/scene/deadramp.js';

const canvas = document.getElementById('scene') as HTMLCanvasElement;
const ctx = canvas.getContext('2d') as CanvasRenderingContext2D;
const titleEl = document.getElementById('build-title') as HTMLDivElement;
const metaEl = document.getElementById('build-meta') as HTMLDivElement;
const statsEl = document.getElementById('stats') as HTMLPreElement;
const statusEl = document.getElementById('status') as HTMLDivElement;

function draw(city: BuiltCity): void {
  const w = (canvas.width = canvas.clientWidth * devicePixelRatio);
  const h = (canvas.height = canvas.clientHeight * devicePixelRatio);
  ctx.fillStyle = '#05070d';
  ctx.fillRect(0, 0, w, h);
  const scale = Math.min(w / (city.extentM.width * 1.5), h / (city.extentM.depth * 1.5 + 160)) ;
  const ox = w / 2;
  const oy = h / 2;
  const sorted = [...city.buildings].sort((a, b) => a.z + a.x - (b.z + b.x));
  for (const b of sorted) {
    const px = ox + (b.x - b.z) * 0.866 * scale;
    const py = oy + (b.x + b.z) * 0.5 * scale;
    const bw = b.w * scale * 0.866;
    const bd = b.d * scale * 0.5;
    const bh = b.height * scale;
    ctx.fillStyle = '#164e63';
    ctx.beginPath();
    ctx.moveTo(px, py - bh);
    ctx.lineTo(px + bw, py - bh + bd);
    ctx.lineTo(px + bw, py + bd);
    ctx.lineTo(px, py);
    ctx.closePath();
    ctx.fill();
    ctx.fillStyle = '#0e7490';
    ctx.beginPath();
    ctx.moveTo(px, py - bh);
    ctx.lineTo(px - bw, py - bh + bd);
    ctx.lineTo(px - bw, py + bd);
    ctx.lineTo(px, py);
    ctx.closePath();
    ctx.fill();
    ctx.fillStyle = '#67e8f9';
    ctx.beginPath();
    ctx.moveTo(px, py - bh);
    ctx.lineTo(px + bw, py - bh + bd);
    ctx.lineTo(px, py - bh + 2 * bd);
    ctx.lineTo(px - bw, py - bh + bd);
    ctx.closePath();
    ctx.fill();
  }
}

async function main(): Promise<void> {
  const res = await fetch('./public/deadramp/accounting-l2.json');
  if (!res.ok) throw new Error(`record fetch failed: ${res.status}`);
  const record = (await res.json()) as DeadRampBuildRecord & {
    title: string; summary: string; testCount: number; specCount: number;
    launchMode: string; http: { operationsTotal: number };
  };
  titleEl.textContent = record.title;
  metaEl.textContent =
    `${record.manifest.length} modules, ${record.http.operationsTotal} operations, ` +
    `${record.testCount} tests, ${record.specCount} source offerings, launch mode ${record.launchMode}. ` +
    `One building per manifest entry; size and height scale with the square root of the entry byte count.`;
  const spec = fitCitySpec(layoutFromDeadRampBuild(record), {
    name: `DeadRamp ${record.groupDir}`,
  });
  const built = buildCity(spec, 20261121);
  const check = checkCityStats(spec, measureCity(built, spec));
  statsEl.textContent =
    `fitted buildings : ${spec.buildingCount}\n` +
    `regenerated      : ${built.buildings.length}\n` +
    `city digest      : ${cityDigest(built)}\n` +
    `statistics oracle: ${check.pass ? 'PASS' : `FAIL (${check.failures.join('; ')})`}`;
  statusEl.textContent = check.pass
    ? 'Regenerated from the fitted spec alone. No DeadRamp geometry was loaded.'
    : 'The regenerated city failed its statistics oracle; see the panel.';
  draw(built);
  addEventListener('resize', () => draw(built));
}

main().catch((e: Error) => {
  statusEl.textContent = `Failed: ${e.message}`;
});
