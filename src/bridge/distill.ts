// bridge/distill.ts - runtime side of V3 distillation.
//
// The foundry (python/xrgen/inverse.py) runs once, offline, and emits a
// plain JSON bundle. This module loads that bundle at runtime through the
// existing mirrors. Hard invariant: NOTHING here depends on NVIDIA,
// Google Colab, DLSS, or any ML framework. The bundle carries numbers;
// this module turns them into a MaterialSpec the WebGL2 renderer already
// knows how to draw, plus optional style-MLP weights for TsMlProvider.
//
// Python float64 <-> TS float64 agreement for distillDetail() is
// bit-exact and unit-tested (test/inverse.test.ts, values generated by
// python/xrgen/inverse.py). The GLSL evaluation is float32 (highp) and
// therefore tolerance-checked, documented in INVERSE.md.
import type { MaterialSpec } from '../material/shader.js';
import type { MlWeights } from './python.js';

/** The fitted detail function inside a bundle. */
export interface DistillDetailParams {
  kind: 'fbm-hhash';
  /** Seed offset in UV space. */
  seed: [number, number];
  scale: number;
  octaves: number;
  /** Per-octave weights, always length 6 (unused octaves are 0). */
  weights: number[];
  bias: number;
}

export interface DistillationBundle {
  format: 'xr-distill/1';
  asset: string;
  engine: 'xr-engine';
  engine_version?: string;
  seed: number;
  material: {
    baseColor: [number, number, number];
    detail: DistillDetailParams;
  };
  /** Style-MLP weights for TsMlProvider, or null when not fitted. */
  heightStyle: MlWeights | null;
  quality: {
    rmse: number;
    score: number;
    coverage: number;
    passed: boolean;
    height_rmse?: number;
  };
  provenance: Record<string, unknown>;
}

/** Float64 reference of the distilled detail multiplier. Bit-exact mirror
 *  of detail_reference() in python/xrgen/inverse.py. Do not "improve"
 *  the arithmetic: any change here must change there too. */
export function distillDetail(u: number, v: number, d: DistillDetailParams): number {
  let total = 0;
  const px = u * d.scale + d.seed[0];
  const py = v * d.scale + d.seed[1];
  let freq = 1;
  for (let o = 0; o < 6; o++) {
    if (o <= d.octaves - 1) {
      total += d.weights[o] * dnoise(px * freq, py * freq);
    }
    freq *= 2.03;
  }
  return d.bias + total;
}

function hfrac(x: number): number {
  return x - Math.floor(x);
}

/** Polynomial cell hash in [0, 1). Bit-exact mirror of _dhash() in
 *  python/xrgen/inverse.py. Uses no transcendental functions: sin()
 *  differs by 1 ulp between CPython and V8 (verified), every op here
 *  is correctly rounded in float64 on both. */
function dhash(px: number, py: number): number {
  let p3x = hfrac(px * 0.1031);
  let p3y = hfrac(py * 0.1031);
  let p3z = hfrac(px * 0.1031);
  const d = p3x * (p3y + 33.33) + p3y * (p3z + 33.33) + p3z * (p3x + 33.33);
  p3x += d;
  p3y += d;
  p3z += d;
  return hfrac((p3x + p3y) * p3z);
}

function dnoise(px: number, py: number): number {
  const ix = Math.floor(px), iy = Math.floor(py);
  const fx = px - ix, fy = py - iy;
  const ux = fx * fx * (3 - 2 * fx);
  const uy = fy * fy * (3 - 2 * fy);
  const a = dhash(ix, iy);
  const b = dhash(ix + 1, iy);
  const c = dhash(ix, iy + 1);
  const d = dhash(ix + 1, iy + 1);
  return a + (b - a) * ux + (c - a) * uy + (a - b - c + d) * ux * uy;
}

function isFiniteNumber(x: unknown): x is number {
  return typeof x === 'number' && Number.isFinite(x);
}

/** Schema + range check. Throws on anything malformed. Mirrors
 *  validate_bundle() in python/xrgen/inverse.py. */
export function validateDistillationBundle(doc: unknown): DistillationBundle {
  if (typeof doc !== 'object' || doc === null) {
    throw new Error('bundle must be an object');
  }
  const b = doc as Record<string, unknown>;
  for (const key of ['format', 'asset', 'engine', 'seed', 'material', 'quality']) {
    if (!(key in b)) throw new Error(`bundle missing required key: ${key}`);
  }
  if (b['format'] !== 'xr-distill/1') {
    throw new Error(`unknown bundle format: ${String(b['format'])}`);
  }
  if (b['engine'] !== 'xr-engine') {
    throw new Error(`bundle is for engine ${String(b['engine'])}, not xr-engine`);
  }
  const mat = b['material'] as Record<string, unknown>;
  const bc = mat['baseColor'] as unknown;
  if (!Array.isArray(bc) || bc.length !== 3 || !bc.every((c) => isFiniteNumber(c) && c >= 0 && c <= 1)) {
    throw new Error('material.baseColor must be [r, g, b] in [0, 1]');
  }
  const det = mat['detail'] as Record<string, unknown>;
  if (det['kind'] !== 'fbm-hhash') {
    throw new Error("material.detail.kind must be 'fbm-hhash'");
  }
  const w = det['weights'] as unknown;
  if (!Array.isArray(w) || w.length !== 6 || !w.every(isFiniteNumber)) {
    throw new Error('material.detail.weights must be 6 finite numbers');
  }
  if (!Number.isInteger(det['octaves']) || (det['octaves'] as number) < 1 || (det['octaves'] as number) > 6) {
    throw new Error('material.detail.octaves must be an int in 1..6');
  }
  const seedArr = det['seed'] as unknown;
  if (!Array.isArray(seedArr) || seedArr.length !== 2 || !seedArr.every(isFiniteNumber)) {
    throw new Error('material.detail.seed must be [x, y]');
  }
  if (!isFiniteNumber(det['scale']) || !isFiniteNumber(det['bias'])) {
    throw new Error('material.detail.scale/bias must be finite numbers');
  }
  const hs = b['heightStyle'] as unknown;
  if (hs !== null && hs !== undefined) {
    const hsr = hs as Record<string, unknown>;
    const arch = hsr['arch'] as unknown;
    if (!Array.isArray(arch) || arch.length !== 3 || arch[0] !== 3 || arch[1] !== 6 || arch[2] !== 1) {
      throw new Error('heightStyle.arch must be [3, 6, 1]');
    }
    for (const key of ['w1', 'b1', 'w2', 'b2']) {
      if (!(key in hsr)) throw new Error(`heightStyle missing ${key}`);
    }
  }
  const q = b['quality'] as Record<string, unknown>;
  for (const key of ['score', 'coverage']) {
    const v = q[key] as unknown;
    if (!isFiniteNumber(v) || v < 0 || v > 1) {
      throw new Error(`quality.${key} must be in [0, 1]`);
    }
  }
  if (typeof q['passed'] !== 'boolean') {
    throw new Error('quality.passed must be a bool');
  }
  return b as unknown as DistillationBundle;
}

/** What the runtime needs: a MaterialSpec the renderer draws as-is, the
 *  uniform values buildMaterial would set (so callers can merge them),
 *  plus optional style weights for TsMlProvider. No ML framework at
 *  runtime: the weights are baked constants, and MLP evaluation is off
 *  when the bundle has none. */
export interface AppliedDistillation {
  spec: MaterialSpec;
  uniforms: Record<string, number | number[]>;
  styleWeights: MlWeights | null;
}

/** Apply a validated bundle. The 'distill' effect evaluates the fitted
 *  detail in the fragment shader from plain uniforms. */
export function applyDistillationBundle(bundle: DistillationBundle): AppliedDistillation {
  const det = bundle.material.detail;
  const spec: MaterialSpec = {
    baseColor: [...bundle.material.baseColor] as [number, number, number],
    effects: ['distill'],
    generatedBy: 'Python (distilled)',
  };
  // Same values buildMaterial() would install as defaults; the real
  // fitted values go here so the spec is complete on its own.
  const uniforms: Record<string, number | number[]> = {
    uDistillSeed: [...det.seed],
    uDistillScale: det.scale,
    uDistillW: [...det.weights],
    uDistillBias: det.bias,
    uDistillOctaves: det.octaves,
  };
  return { spec, uniforms, styleWeights: bundle.heightStyle ?? null };
}

/** Fetch a bundle JSON (foundry output, served next to the demo or
 *  inlined at build time) and validate it. */
export async function loadDistillationBundle(url: string): Promise<DistillationBundle> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`distillation bundle not found: ${url}`);
  return validateDistillationBundle(await res.json());
}
